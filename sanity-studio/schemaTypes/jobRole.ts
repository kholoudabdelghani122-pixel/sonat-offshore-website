import {defineField, defineType} from 'sanity'

export default defineType({
  name: 'jobRole',
  title: 'Job Role',
  type: 'document',
  groups: [
    {name: 'listing', title: 'Listing', default: true},
    {name: 'details', title: 'Job brief'},
    {name: 'publishing', title: 'Publishing'},
  ],
  fields: [
    defineField({
      name: 'title',
      title: 'Role title',
      type: 'string',
      group: 'listing',
      validation: (rule) => rule.required().max(120),
    }),
    defineField({
      name: 'slug',
      title: 'URL slug',
      type: 'slug',
      group: 'listing',
      options: {source: 'title', maxLength: 96},
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: 'discipline',
      title: 'Discipline',
      type: 'string',
      group: 'listing',
      options: {
        list: [
          {title: 'Rig Operations', value: 'rig-operations'},
          {title: 'Project Management', value: 'project-management'},
          {title: 'Asset Management', value: 'asset-management'},
          {title: 'Well Control / Subsea', value: 'well-control-subsea'},
          {title: 'Inspection & Surveys', value: 'inspection-surveys'},
          {title: 'Project Controls', value: 'project-controls'},
          {title: 'HSE', value: 'hse'},
          {title: 'Other', value: 'other'},
        ],
      },
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: 'roleType',
      title: 'Role type',
      description: 'For example: Permanent, Contract, or Talent Pool.',
      type: 'string',
      group: 'listing',
      validation: (rule) => rule.max(60),
    }),
    defineField({
      name: 'location',
      title: 'Location',
      type: 'string',
      group: 'listing',
      validation: (rule) => rule.max(100),
    }),
    defineField({
      name: 'summary',
      title: 'Accordion subtitle',
      description: 'Short line shown beneath the role title, such as “Operations · Talent Pool”.',
      type: 'string',
      group: 'listing',
      validation: (rule) => rule.required().max(160),
    }),
    defineField({
      name: 'description',
      title: 'Job brief',
      type: 'array',
      group: 'details',
      of: [
        {type: 'block', styles: [{title: 'Normal', value: 'normal'}, {title: 'Heading 2', value: 'h2'}, {title: 'Heading 3', value: 'h3'}, {title: 'Quote', value: 'blockquote'}]},
        {type: 'image', options: {hotspot: true}},
      ],
      validation: (rule) => rule.required().min(1),
    }),
    defineField({
      name: 'responsibilities',
      title: 'Responsibilities',
      type: 'array',
      group: 'details',
      of: [{type: 'string'}],
    }),
    defineField({
      name: 'qualifications',
      title: 'Qualifications',
      type: 'array',
      group: 'details',
      of: [{type: 'string'}],
    }),
    defineField({
      name: 'status',
      title: 'Status',
      description: 'Only published roles marked Open should be presented as current vacancies.',
      type: 'string',
      group: 'publishing',
      initialValue: 'talent-pool',
      options: {
        list: [
          {title: 'Talent Pool', value: 'talent-pool'},
          {title: 'Open', value: 'open'},
          {title: 'Closed', value: 'closed'},
        ],
        layout: 'radio',
      },
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: 'sortOrder',
      title: 'Sort order',
      type: 'number',
      group: 'publishing',
      description: 'Optional manual order in the careers list; lower numbers appear first.',
      validation: (rule) => rule.integer().min(0),
    }),
    defineField({
      name: 'publishedAt',
      title: 'Publication date',
      type: 'datetime',
      group: 'publishing',
    }),
    defineField({
      name: 'closingDate',
      title: 'Closing date',
      type: 'datetime',
      group: 'publishing',
    }),
  ],
  preview: {
    select: {title: 'title', subtitle: 'summary'},
  },
})
